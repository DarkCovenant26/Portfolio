import type { Metadata } from "next";

// The site's public URL: the production domain, which Vercel's Standard Protection leaves
// public (generated deployment URLs sit behind a login). Set NEXT_PUBLIC_SITE_URL to move
// to a custom domain. VERCEL_PROJECT_PRODUCTION_URL isn't used because Vercel picks the
// shortest production domain, which may not be this one.
export const SITE_URL = process.env.NEXT_PUBLIC_SITE_URL ?? "https://zandronarvaza-portfolio.vercel.app";

export const SITE_NAME = "Zandro E. Narvaza";
export const SITE_TITLE = "Zandro E. Narvaza | Director of Cyber R&D & Systems Architect";
export const SITE_DESCRIPTION =
    "Director of Cyber R&D and full-stack architect in Cagayan de Oro, Philippines, building secure multi-tenant cyber security platforms with Django, FastAPI, Next.js and Kubernetes.";

// The site-wide share image generated by app/opengraph-image.tsx; pages with their
// own generated image (project pages) pass its path as `image`
const SHARE_IMAGE_PATH = "/opengraph-image";

// Next.js replaces (not merges) a parent's openGraph when a page sets its own, and a
// layout with a plain-string title cuts off the root title template for its children,
// so every page spells out its full title, canonical URL, share text and image.
export function pageMetadata({
    title,
    description,
    path,
    absoluteTitle = false,
    type = "website",
    image = SHARE_IMAGE_PATH,
}: {
    title: string;
    description: string;
    path: string;
    absoluteTitle?: boolean;
    type?: "website" | "article";
    image?: string;
}): Metadata {
    const fullTitle = absoluteTitle ? title : `${title} | ${SITE_NAME}`;
    const shareImage = { url: image, width: 1200, height: 630, alt: fullTitle };
    return {
        title: { absolute: fullTitle },
        description,
        alternates: { canonical: path },
        openGraph: {
            title: fullTitle,
            description,
            url: path,
            siteName: SITE_NAME,
            locale: "en_US",
            type,
            images: [shareImage],
        },
        twitter: {
            card: "summary_large_image",
            title: fullTitle,
            description,
            images: [shareImage.url],
        },
    };
}
